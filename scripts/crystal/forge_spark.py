#!/usr/bin/env python3
"""FORGE: deterministic first-generation Crystal Spark factory.

Build-time only. It creates a new Spark package from a small YAML idea and a
factory profile. It never overwrites an existing package.
"""

from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
from typing import Any

import yaml


REQUIRED = ("id", "name", "class", "purpose")


def sha256_text(value: str) -> str:
    return hashlib.sha256(value.encode("utf-8")).hexdigest()


def load_yaml(path: Path) -> dict[str, Any]:
    with path.open("r", encoding="utf-8") as handle:
        value = yaml.safe_load(handle)
    if not isinstance(value, dict):
        raise ValueError(f"expected mapping: {path}")
    return value


def validate_idea(idea: dict[str, Any]) -> None:
    missing = [key for key in REQUIRED if not str(idea.get(key, "")).strip()]
    if missing:
        raise ValueError("missing required fields: " + ", ".join(missing))
    spark_id = str(idea["id"])
    if not spark_id.replace("-", "").replace("_", "").isalnum():
        raise ValueError("id must contain only letters, numbers, '-' or '_'")


def dump(value: dict[str, Any]) -> str:
    return yaml.safe_dump(value, sort_keys=False, allow_unicode=False)


def generate(idea: dict[str, Any], profile: dict[str, Any], factory_version: str) -> dict[str, str]:
    spark_id = str(idea["id"])
    source = dump(idea)
    source_hash = sha256_text(source)

    identity = {
        "schema": "crystal.spark.identity.v1",
        "id": spark_id,
        "name": idea["name"],
        "class": idea["class"],
        "namespace": profile["identity"]["namespace"],
        "source_idea_sha256": source_hash,
    }
    capabilities = {
        "schema": "crystal.spark.capabilities.v1",
        "capabilities": idea.get("capabilities", []),
        "default": "deny",
    }
    policy = {
        "schema": "crystal.spark.policy.v1",
        "trust_boundary": profile["security"]["trust_boundary"],
        "network": profile["security"]["network_default"],
        "encryption": profile["security"]["encryption_default"],
        "least_privilege": profile["security"]["least_privilege"],
    }
    runtime = {
        "schema": "crystal.spark.runtime.v1",
        "entrypoint": idea.get("entrypoint"),
        "environment": {},
    }
    experience = {
        "schema": "crystal.spark.experience.v1",
        "owner": profile["experience"]["owner"],
        "ui_namespace": f"{profile['experience']['ui_namespace']}.{spark_id}",
        "dashboard_integration": profile["experience"]["dashboard_integration"],
    }
    lifecycle = {
        "schema": "crystal.spark.lifecycle.v1",
        "state": profile["lifecycle"]["initial_state"],
        "terminal_states": profile["lifecycle"]["terminal_states"],
    }
    evidence = {
        "schema": "crystal.spark.evidence.v1",
        "required": profile["verification"]["required"],
        "factory_version": factory_version,
        "source_idea_sha256": source_hash,
    }
    manifest = {
        "schema": "crystal.spark.v1",
        "id": spark_id,
        "name": idea["name"],
        "purpose": idea["purpose"],
        "factory": factory_version,
    }
    ui = {
        "schema": "crystal.spark.ui-manifest.v1",
        "spark": spark_id,
        "namespace": experience["ui_namespace"],
        "entry": "index",
    }
    readme = f"# {idea['name']}\n\n{idea['purpose']}\n\nGenerated by FORGE {factory_version}.\n"
    test = """def test_spark_contract_files_exist():\n    from pathlib import Path\n    root = Path(__file__).parents[1]\n    for name in (\n        \"spark.yaml\", \"identity.yaml\", \"capabilities.yaml\",\n        \"policy.yaml\", \"runtime.yaml\", \"experience.yaml\",\n        \"lifecycle.yaml\", \"evidence.yaml\",\n    ):\n        assert (root / name).is_file(), name\n"""

    return {
        "spark.yaml": dump(manifest),
        "identity.yaml": dump(identity),
        "capabilities.yaml": dump(capabilities),
        "policy.yaml": dump(policy),
        "runtime.yaml": dump(runtime),
        "experience.yaml": dump(experience),
        "lifecycle.yaml": dump(lifecycle),
        "evidence.yaml": dump(evidence),
        "README.md": readme,
        "tests/contract_test.py": test,
        "ui/manifest.yaml": dump(ui),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="FORGE a new Crystal Spark")
    parser.add_argument("idea", type=Path)
    parser.add_argument("--profile", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--factory-version", default="forge-spark-v1")
    args = parser.parse_args()

    idea = load_yaml(args.idea)
    profile = load_yaml(args.profile)
    validate_idea(idea)

    target = (args.output / str(idea["id"])).resolve()
    output_root = args.output.resolve()
    if output_root not in target.parents:
        raise ValueError("output path escapes factory root")
    if target.exists():
        raise FileExistsError(f"refusing to overwrite existing Spark: {target}")

    files = generate(idea, profile, args.factory_version)
    for relative, content in files.items():
        destination = target / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(content, encoding="utf-8")

    print(target)
    print(f"generated {len(files)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
